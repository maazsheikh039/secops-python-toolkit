#!/usr/bin/env python3
"""
Analyze alerts generated by the monitoring daemon
"""

def analyze_alerts(alert_file):
    """
    Analyze alert file and generate statistics
    
    Args:
        alert_file: Path to alerts log file
    """
    try:
        with open(alert_file, 'r') as f:
            lines = f.readlines()
        
        error_count = 0
        critical_count = 0
        
        for line in lines:
            if 'ERROR:' in line:
                error_count += 1
            elif 'CRITICAL:' in line:
                critical_count += 1
        
        print("=" * 50)
        print("ALERT STATISTICS")
        print("=" * 50)
        print(f"Total Alerts: {len(lines)}")
        print(f"ERROR Alerts: {error_count}")
        print(f"CRITICAL Alerts: {critical_count}")
        print("=" * 50)
        
    except FileNotFoundError:
        print(f"Alert file not found: {alert_file}")

if __name__ == "__main__":
    analyze_alerts("output/alerts.log")
